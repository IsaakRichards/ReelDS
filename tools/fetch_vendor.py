#!/usr/bin/env python3
"""
Fills vendor/ with everything the encoder needs, for every supported platform:

  vendor/<platform>/python.tar.gz   portable CPython (astral-sh/python-build-standalone)
  vendor/<platform>/wheels/*.whl    numpy, Pillow, imageio-ffmpeg (ships an ffmpeg binary)
  vendor/<platform>/VERSION         bumps whenever the bundle changes (launchers re-unpack)

Run by .github/workflows/vendor.yml; needs network access, `gh` (or GH_TOKEN) and pip.
"""
import argparse
import datetime
import json
import os
import re
import shutil
import subprocess
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VENDOR = ROOT / "vendor"
REQS = ["numpy>=1.23", "pillow>=10.1", "imageio-ffmpeg>=0.5"]
MAX_FILE = 95 * 1024 * 1024   # GitHub rejects files over 100 MB

PLATFORMS = {
    "windows-x64": {"triple": "x86_64-pc-windows-msvc", "wheel": ["win_amd64"]},
    "linux-x64": {"triple": "x86_64-unknown-linux-gnu",
                  "wheel": ["manylinux_2_28_x86_64", "manylinux_2_27_x86_64",
                            "manylinux_2_17_x86_64", "manylinux2014_x86_64"]},
    "macos-arm64": {"triple": "aarch64-apple-darwin",
                    "wheel": ["macosx_13_0_arm64", "macosx_12_0_arm64", "macosx_11_0_arm64"]},
    "macos-x64": {"triple": "x86_64-apple-darwin",
                  "wheel": ["macosx_11_0_x86_64", "macosx_10_13_x86_64", "macosx_10_12_x86_64",
                            "macosx_10_9_x86_64", "macosx_10_9_intel"]},
}


def gh_api(path):
    out = subprocess.run(["gh", "api", path], capture_output=True, text=True, check=True)
    return json.loads(out.stdout)


def download(url, dest):
    print(f"  downloading {url.rsplit('/', 1)[-1]}")
    with urllib.request.urlopen(url) as r, open(dest, "wb") as f:
        shutil.copyfileobj(r, f)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--python", default="3.12", help="CPython minor version, e.g. 3.12")
    ap.add_argument("--only", nargs="*", help="platform names to (re)fetch")
    a = ap.parse_args()

    rel = gh_api("repos/astral-sh/python-build-standalone/releases/latest")
    tag = rel["tag_name"]
    pat = re.compile(rf"^cpython-({re.escape(a.python)}\.\d+)\+{tag}-(.+)-install_only_stripped\.tar\.gz$")
    assets = {}
    for asset in rel["assets"]:
        m = pat.match(asset["name"])
        if m:
            assets[m.group(2)] = (m.group(1), asset["browser_download_url"])
    pyver = a.python.replace(".", "")
    stamp = datetime.date.today().isoformat()
    summary = []

    for name, cfg in PLATFORMS.items():
        if a.only and name not in a.only:
            continue
        print(f"== {name}")
        if cfg["triple"] not in assets:
            sys.exit(f"no python-build-standalone asset for {cfg['triple']} in {tag}")
        full, url = assets[cfg["triple"]]
        d = VENDOR / name
        shutil.rmtree(d, ignore_errors=True)
        (d / "wheels").mkdir(parents=True)
        download(url, d / "python.tar.gz")

        cmd = [sys.executable, "-m", "pip", "download", "--only-binary=:all:", "--no-cache-dir",
               "--python-version", a.python, "--implementation", "cp",
               "--abi", f"cp{pyver}", "--abi", "abi3", "--abi", "none", "-d", str(d / "wheels")]
        for p in cfg["wheel"]:
            cmd += ["--platform", p]
        subprocess.run(cmd + REQS, check=True)

        wheels = sorted(p.name for p in (d / "wheels").glob("*.whl"))
        for want in ("numpy-", "pillow-", "imageio_ffmpeg-"):
            if not any(w.lower().startswith(want) for w in wheels):
                sys.exit(f"{name}: missing wheel {want}* (got {wheels})")
        for f in d.rglob("*"):
            if f.is_file() and f.stat().st_size > MAX_FILE:
                sys.exit(f"{f} is too large for GitHub ({f.stat().st_size >> 20} MB)")
        (d / "VERSION").write_text(f"py{full}-{stamp}\n")
        size = sum(f.stat().st_size for f in d.rglob("*") if f.is_file()) >> 20
        summary.append(f"| {name} | CPython {full} | {', '.join(wheels)} | {size} MB |")

    (VENDOR / "README.md").write_text(
        "# Bundled encoder dependencies\n\n"
        "Generated by `tools/fetch_vendor.py` (workflow *Vendor dependencies*). The `reelds.cmd` /\n"
        "`reelds.sh` launchers pick the folder for your OS/CPU and unpack it into `.runtime/`.\n\n"
        "| platform | python | wheels | size |\n|---|---|---|---|\n" + "\n".join(summary) + "\n\n"
        "Licenses: CPython (PSF License, via astral-sh/python-build-standalone), NumPy (BSD-3-Clause),\n"
        "Pillow (MIT-CMU), imageio-ffmpeg (BSD-2-Clause) which contains an FFmpeg binary\n"
        "(GPL; sources at https://ffmpeg.org, build details at https://github.com/imageio/imageio-ffmpeg).\n")
    print("done")


if __name__ == "__main__":
    main()
